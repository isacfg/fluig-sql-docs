-- workflow/pending_tasks_by_user: Listar tarefas pendentes de um usuário
-- Result grain: one task assignment (five-column TAR_PROCES PK)
-- Dialect: MySQL; bind named parameters through your driver (do not interpolate).
-- Validation: static schema checks only; not executed on a Fluig database.
SELECT TAR_PROCES.COD_EMPRESA, TAR_PROCES.NUM_PROCES, TAR_PROCES.NUM_SEQ_MOVTO, TAR_PROCES.NUM_SEQ_TRANSF,
       TAR_PROCES.CD_MATRICULA, TAR_PROCES.IDI_STATUS, TAR_PROCES.START_DATE, TAR_PROCES.DEADLINE, PROCES_WORKFLOW.COD_DEF_PROCES
FROM TAR_PROCES
JOIN PROCES_WORKFLOW ON PROCES_WORKFLOW.COD_EMPRESA = TAR_PROCES.COD_EMPRESA AND PROCES_WORKFLOW.NUM_PROCES = TAR_PROCES.NUM_PROCES
WHERE TAR_PROCES.COD_EMPRESA = :tenant_id AND TAR_PROCES.CD_MATRICULA = :user_code
  AND TAR_PROCES.LOG_ATIV = 1 AND TAR_PROCES.IDI_STATUS IN (0, 1)
ORDER BY TAR_PROCES.DEADLINE, TAR_PROCES.NUM_PROCES, TAR_PROCES.NUM_SEQ_MOVTO, TAR_PROCES.NUM_SEQ_TRANSF;
