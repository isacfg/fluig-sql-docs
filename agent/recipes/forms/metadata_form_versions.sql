-- forms/metadata_form_versions: Listar versões de formulário de metadados com documento
-- Result grain: one metadata-form version
-- Dialect: MySQL; bind named parameters through your driver (do not interpolate).
-- Validation: static schema checks only; not executed on a Fluig database.
SELECT ECM_METADATA_FORM.TENANT_ID, ECM_METADATA_FORM.ID, ECM_METADATA_FORM.TITLE, ECM_METADATA_FORM.DOCUMENT_ID, ECM_METADATA_FORM.DCMNT_VRSN_NMBER,
       ECM_METADATA_FORM.VERSION_STATUS, DOCUMENTO.DS_PRINCIPAL_DOCUMENTO, DOCUMENTO.LOG_DELETE
FROM ECM_METADATA_FORM
JOIN DOCUMENTO ON DOCUMENTO.COD_EMPRESA = ECM_METADATA_FORM.TENANT_ID AND DOCUMENTO.NR_DOCUMENTO = ECM_METADATA_FORM.DOCUMENT_ID
  AND DOCUMENTO.NR_VERSAO = ECM_METADATA_FORM.DCMNT_VRSN_NMBER
WHERE ECM_METADATA_FORM.TENANT_ID = :tenant_id AND ECM_METADATA_FORM.DOCUMENT_ID = :document_id
ORDER BY ECM_METADATA_FORM.DCMNT_VRSN_NMBER;
